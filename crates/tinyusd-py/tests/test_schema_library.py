import json
from pathlib import Path

import numpy as np
import pytest

import tinyusd

DATA = Path(__file__).resolve().parents[3] / "tests" / "data"
USD = DATA / "openusd-26.11.1"
FAMILIES = ["usd", "usdGeom", "usdShade", "usdVol", "usdLux", "usdRender", "usdPhysics"]

pytestmark = pytest.mark.skipif("schemas" not in tinyusd.features(), reason="built without schemas")


def read(family):
    return tinyusd.read_schema_library(USD / family / "schema.usda", [USD])


def test_reads_every_library():
    for family in FAMILIES:
        library = read(family)
        assert library.name == family
        assert library.classes
        assert library.global_data["libraryName"] == family


def test_classes_and_properties():
    geom = read("usdGeom")
    assert geom.prefix == "UsdGeom"
    mesh = geom.find_class("Mesh")
    assert mesh.kind == "concreteTyped" and mesh.cpp_name == "UsdGeomMesh"
    assert mesh.bases == ["PointBased", "Gprim", "Boundable", "Xformable", "Imageable", "Typed"]
    scheme = mesh.find_property("subdivisionScheme")
    assert (scheme.declared_by, scheme.type_name, scheme.uniform) == ("Mesh", "token", True)
    assert scheme.fallback == "catmullClark"
    assert scheme.allowed_tokens == ["catmullClark", "loop", "bilinear", "none"]
    assert mesh.find_property("points").declared_by == "PointBased"
    assert mesh.find_property("primvars:displayColor").custom_data == {"apiName": "displayColor"}
    assert mesh.find_property("proxyPrim").relationship
    plate = geom.find_class("BackPlateAPI")
    assert plate.kind == "multipleApplyAPI" and plate.property_namespace_prefix == "backPlate"
    np.testing.assert_array_equal(plate.find_property("scale:tweak").fallback, [1.0, 1.0])
    assert geom.find_class("VisibilityAPI").can_only_apply_to == ["Imageable"]
    assert any(t.name == "interpolation" for t in geom.tokens)
    assert "interpolation" in geom.global_data["libraryTokens"]

    lux = read("usdLux")
    intensity = lux.find_class("LightAPI").find_property("inputs:intensity")
    assert (intensity.display_group, intensity.display_name, intensity.fallback) == ("Basic", "Intensity", 1.0)
    assert "LightAPI" in lux.find_class("DomeLight").api_schemas

    shade = read("usdShade")
    material = shade.find_class("Material")
    assert material.custom_data["extraPlugInfo"]["providesUsdShadeConnectableAPIBehavior"] is True
    assert shade.find_class("Shader").api_schemas == ["NodeDefAPI"]


def test_shader_defs():
    nodes = tinyusd.read_shader_defs(USD / "usdShaders" / "shaderDefs.usda", [USD])
    by_id = {n.id: n for n in nodes}
    surface = by_id["UsdPreviewSurface"]
    roughness = next(p for p in surface.inputs if p.name == "roughness")
    assert roughness.type_name == "float" and roughness.fallback == 0.5
    texture = by_id["UsdUVTexture"]
    assert texture.sdr_metadata == {"role": "texture"}
    wrap = next(p for p in texture.inputs if p.name == "wrapS")
    assert "repeat" in wrap.allowed_tokens
    assert all(p.type_name for n in nodes for p in n.inputs + n.outputs)


def compare_prims(ours, theirs):
    assert ours.type_name == theirs.type_name
    assert ours.applied_schemas == theirs.applied_schemas
    for key in ("customData:userDocBrief", "customData:apiSchemaOverridePropertyNames"):
        assert ours.metadata(key) == theirs.metadata(key), (theirs.path, key)
    names = theirs.attribute_names(authored_only=True)
    assert ours.attribute_names(authored_only=True) == names
    assert ours.relationship_names(authored_only=True) == theirs.relationship_names(authored_only=True)
    for name in names:
        a, b = ours.attribute_info(name), theirs.attribute_info(name)
        assert (a.type_name, a.uniform) == (b.type_name, b.uniform), (theirs.path, name)
        np.testing.assert_equal(ours.get(name), theirs.get(name))
        brief = "customData:userDocBrief"
        assert ours.attribute_metadata(name, brief) == theirs.attribute_metadata(name, brief)


def plug_types(path):
    text = "\n".join(line for line in path.read_text().splitlines() if not line.lstrip().startswith("#"))
    types = json.loads(text)["Plugins"][0]["Info"]["Types"]
    return {name: entry for name, entry in types.items() if entry.get("autoGenerated")}


def test_written_plugins_match_usd(tmp_path):
    for family in FAMILIES:
        library = read(family)
        library.write_plugin(tmp_path / family)
        ours = tinyusd.Stage.open(tmp_path / family / "generatedSchema.usda")
        theirs = tinyusd.Stage.open(USD / family / "generatedSchema.usda")
        prims = theirs.traverse(include_abstract=True)
        assert len(prims) == len(ours.traverse(include_abstract=True))
        for prim in prims:
            compare_prims(ours.prim(prim.path), prim)
        assert plug_types(tmp_path / family / "plugInfo.json") == plug_types(USD / family / "plugInfo.json")


def test_schema_paths_replace_builtin_families():
    def tweak(schemas):
        stage = tinyusd.Stage.open(DATA / "backplate.usda", schemas=schemas)
        camera = stage.prim("/Camera")
        assert camera.is_a("Camera")
        return camera.get("backPlate:plate:scale:tweak")

    assert tweak([]) is None
    np.testing.assert_array_equal(tweak([USD / "usdGeom"]), [1.0, 1.0])
    np.testing.assert_array_equal(tweak([USD / f for f in FAMILIES]), [1.0, 1.0])


def test_missing_library():
    with pytest.raises(tinyusd.SchemaError):
        tinyusd.read_schema_library(USD / "nope" / "schema.usda")


def test_read_schema_plugin_matches_the_written_library(tmp_path):
    geom = read("usdGeom")
    geom.write_plugin(tmp_path / "usdGeom")
    plugin = tinyusd.read_schema_plugin(tmp_path / "usdGeom")
    assert plugin.name == "usdGeom"
    for name in ("Sphere", "Mesh", "VisibilityAPI", "BackPlateAPI"):
        ours, theirs = plugin.find_class(name), geom.find_class(name)
        assert (ours.kind, ours.bases[:1], ours.can_only_apply_to) == (theirs.kind, theirs.bases[:1], theirs.can_only_apply_to)
        assert sorted(p.name for p in ours.properties) == sorted(p.name for p in theirs.properties)
    sphere = plugin.find_class("Sphere")
    assert sphere.find_property("radius").fallback == 1.0
    assert sphere.find_property("extent").declared_by == "Sphere"
    assert sphere.find_property("visibility").declared_by == "Imageable"
    assert plugin.find_class("BackPlateAPI").property_namespace_prefix == "backPlate"


